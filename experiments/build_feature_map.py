SEQ = {"A": ("a", "LogReg — решение A"), "B": ("b", "монотонный LightGBM — решение B"),
       "C": ("c", "LightGBM, учит деньгам — решение C")}


def main():
    e = pd.read_csv(R / "experiments.csv", encoding="utf-8")
    seq = e[e["added_feature"].notna() & (e["added_feature"] != "(старт)")]
    seq = seq[(seq["config"] != "a") | (seq["policy"] == "ev_cap")]
    last = lambda cfg, f: seq[(seq["config"] == cfg) & (seq["added_feature"] == f)].tail(1)
    leak = pd.read_csv(R / "leak_tests.csv", encoding="utf-8").groupby("feature")["pass"].all()
    final = set(__import__("src.evaluate", fromlist=["feature_list"]).feature_list(load_config(ROOT / "configs" / "final.yaml")))

    rows = []
    for f, (own, sc, hyp, catch, src, win, nohist, kaggle, why) in T.items():
        cfg, where = SEQ[own]
        r = last(cfg, f)
        r2 = last("a_lgbm", f) if own == "A" else None
        fmt = lambda x: "" if x is None or x.empty else (f"{x['delta_savings'].iloc[0]:+,.0f} "
                                                         f"[{x['delta_ci_low'].iloc[0]:,.0f}; {x['delta_ci_high'].iloc[0]:,.0f}]"
                                                         ).replace(",", " ")
        rows.append({"признак": f, "автор": own, "сценарий": sc, "гипотеза": hyp, "какую операцию ловит": catch,
                     "из чего считается": src, "окно": win, "нет истории": nohist,
                     "тест на утечку": "пройден" if leak.get(f, False) else "НЕ ПРОЙДЕН",
                     "вклад, у.е. [90% интервал]": fmt(r), "где мерили": where,
                     "вклад, у.е. — те же признаки A на LightGBM": fmt(r2) if own == "A" else "",
                     "Δ PR-AUC": "" if r.empty else f"{r['delta_pr_auc'].iloc[0]:+.4f}",
                     "в финале": "да" if f in final else "нет",
                     "почему": why, "чем отличается от типичного решения на Kaggle": kaggle})
    fm = pd.DataFrame(rows)
    fm.to_csv(R / "feature_map.csv", index=False, encoding="utf-8-sig")
    head = ["# Карта признаков", "",
            "Вклад — изменение экономии на valid (21.02–21.04.2020) при добавлении признака к предыдущим, по одному, "
            "в порядке таблицы. В скобках — 90% интервал (бутстрэп по дням). Интервал, задевающий ноль, = «в пределах шума». "
            "Числа собраны скриптом из reports/experiments.csv.", "",
            "Подготовка сырых полей (не синтез): amt, log_amt, category, hour, dow, is_night, is_online, age, gender_m, log_city_pop.",
            ""]
    (R / "feature_map.md").write_text("\n".join(head) + fm.to_markdown(index=False), encoding="utf-8")
    print(fm[["признак", "тест на утечку", "вклад, у.е. [90% интервал]", "где мерили", "в финале"]].to_string())


if __name__ == "__main__":
    main()
