def bg(slide, color):
    f = slide.background.fill
    f.solid()
    f.fore_color.rgb = color


def text(slide, x, y, w, h, runs, size=16, color=INK, font=BODY, bold=False, align=PP_ALIGN.LEFT,
         anchor=MSO_ANCHOR.TOP, spacing=None):
    """runs: строка или список абзацев; абзац — строка или список (текст, {опции})."""
    tb = slide.shapes.add_textbox(Inches(x), Inches(y), Inches(w), Inches(h))
    tf = tb.text_frame
    tf.word_wrap = True
    tf.margin_left = tf.margin_right = tf.margin_top = tf.margin_bottom = 0
    tf.vertical_anchor = anchor
    paras = runs if isinstance(runs, list) else [runs]
    for i, para in enumerate(paras):
        p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
        p.alignment = align
        if spacing:
            p.space_after = Pt(spacing)
        parts = para if isinstance(para, list) else [(para, {})]
        for t, o in parts:
            r = p.add_run()
            r.text = t
            r.font.name = o.get("font", font)
            r.font.size = Pt(o.get("size", size))
            r.font.bold = o.get("bold", bold)
            r.font.italic = o.get("italic", False)
            r.font.color.rgb = o.get("color", color)
    return tb


def box(slide, x, y, w, h, fill=CARD, shape=MSO_SHAPE.ROUNDED_RECTANGLE, radius=0.06, line=None):
    s = slide.shapes.add_shape(shape, Inches(x), Inches(y), Inches(w), Inches(h))
    s.fill.solid()
    s.fill.fore_color.rgb = fill
    if line:
        s.line.color.rgb = line
        s.line.width = Pt(1.25)
    else:
        s.line.fill.background()
    s.shadow.inherit = False
    if shape == MSO_SHAPE.ROUNDED_RECTANGLE:
        s.adjustments[0] = radius
    return s


def badge(slide, x, y, letter, color, d=0.62, size=22):
    c = box(slide, x, y, d, d, fill=color, shape=MSO_SHAPE.OVAL)
    tf = c.text_frame
    tf.margin_left = tf.margin_right = tf.margin_top = tf.margin_bottom = 0
    p = tf.paragraphs[0]
    p.alignment = PP_ALIGN.CENTER
    r = p.add_run()
    r.text = letter
    r.font.name, r.font.size, r.font.bold, r.font.color.rgb = HEAD, Pt(size), True, WHITE
    tf.vertical_anchor = MSO_ANCHOR.MIDDLE
    return c


def title(slide, t, sub=None, color=INK):
    text(slide, 0.6, 0.45, 12.1, 0.8, t, size=34, font=HEAD, bold=True, color=color)
    if sub:
        text(slide, 0.6, 1.2, 12.1, 0.5, sub, size=16, color=MUTED if color == INK else ON_DARK_MUTED)


def speaker(slide, who):
    text(slide, 10.9, 7.0, 1.9, 0.3, f"говорит: {who}", size=10, color=GREY, align=PP_ALIGN.RIGHT)


def bar_chart(slide, x, y, w, h, cats, vals, colors, fmt='# ##0', font_size=12, max_v=None):
    cd = CategoryChartData()
    cd.categories = cats
    cd.add_series("у.е.", vals)
    gf = slide.shapes.add_chart(XL_CHART_TYPE.BAR_CLUSTERED, Inches(x), Inches(y), Inches(w), Inches(h), cd)
    ch = gf.chart
    ch.has_legend = False
    ch.has_title = False
    plot = ch.plots[0]
    plot.gap_width = 45
    plot.has_data_labels = True
    dl = plot.data_labels
    dl.number_format = fmt
    dl.number_format_is_linked = False
    dl.position = XL_LABEL_POSITION.OUTSIDE_END
    dl.font.size = Pt(font_size)
    dl.font.name = BODY
    dl.font.bold = True
    dl.font.color.rgb = INK
    va = ch.value_axis
    va.visible = False
    va.has_major_gridlines = False
    va.minimum_scale = 0
    if max_v:
        va.maximum_scale = max_v
    ca = ch.category_axis
    ca.reverse_order = True
    ca.tick_labels.font.size = Pt(font_size)
    ca.tick_labels.font.name = BODY
    ca.tick_labels.font.color.rgb = INK
    ca.format.line.fill.background()
    ca.has_major_gridlines = False
    for i, pt in enumerate(plot.series[0].points):
        pt.format.fill.solid()
        pt.format.fill.fore_color.rgb = colors[i]
    return ch


